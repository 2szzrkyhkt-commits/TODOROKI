import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const root=process.cwd(),out='quality-results';await fs.mkdir(out,{recursive:true});
const server=http.createServer(async(req,res)=>{try{
 let p=decodeURIComponent(new URL(req.url,'http://local').pathname);if(!path.extname(p))p+='.html';
 const file=path.resolve(root,'.'+p);if(!file.startsWith(root+path.sep))throw Error('outside');
 res.setHeader('Content-Type',p.endsWith('.mjs')||p.endsWith('.js')?'text/javascript':p.endsWith('.css')?'text/css':'text/html');res.end(await fs.readFile(file));
}catch{res.writeHead(404).end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));const origin='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch(),evidence=[];
try{for(const width of [390,1440]){
 const context=await browser.newContext({viewport:{width,height:900}});
 await context.route('**/*',r=>r.request().url().startsWith(origin)?r.continue():r.abort());
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/tax-study');const input=page.locator('#taxable-income');await page.locator('#income-tax-example').waitFor();
 assert.equal(await input.isEnabled(),true);
 assert.equal(await page.locator('#income-tax-result').isVisible(),false);
 await input.fill('7,000,999');await page.getByRole('button',{name:'所得税額を計算',exact:true}).click();
 assert.equal(await page.locator('#income-tax-amount').innerText(),'974,000円');
 assert.equal(await page.locator('#taxable-rounded').innerText(),'7,000,000円');
 assert.equal(await page.locator('#tax-rounding').innerText(),'999円');
 await input.fill('3,300,000');assert.equal(await page.locator('#income-tax-result').isVisible(),false);
 await input.press('Enter');assert.equal(await page.locator('#income-tax-amount').innerText(),'232,500円');
 await input.fill('1e6');await input.press('Enter');assert.equal(await input.getAttribute('aria-invalid'),'true');
 assert.equal(await page.locator('#income-tax-result').isVisible(),false);assert.ok(await page.locator('#income-tax-error').innerText());
 await input.fill('330000001');await input.press('Enter');assert.ok((await page.locator('#income-tax-error').innerText()).includes('入力範囲'));
 await page.locator('#income-tax-example').click();assert.equal(await page.locator('#income-tax-amount').innerText(),'974,000円');
 assert.ok((await page.locator('#income-tax-result').innerText()).includes('復興特別所得税などは含まれていません'));
 await page.getByRole('button',{name:'入力を消す',exact:true}).click();assert.equal(await input.inputValue(),'');
 assert.equal(await page.locator('#income-tax-result').isVisible(),false);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2),false);
 assert.deepEqual(errors,[]);
 await page.locator('#income-tax-example').click();await page.screenshot({path:out+'/income-tax-'+width+'.png',fullPage:true});
 evidence.push({width,example:974000,boundary:232500,rounding:999,staleResultCleared:true,invalidInputsRejected:true,reset:true,overflow:false,pageErrors:errors});
 await context.close();
}}finally{await fs.writeFile(out+'/income-tax-ui.json',JSON.stringify(evidence,null,2));await browser.close();await new Promise(r=>server.close(r));}
console.log('T22 income-tax UI: 390/1440px, calculation, boundary, rounding, stale result, invalid input, reset, keyboard and overflow passed.');
